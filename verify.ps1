# PowerShell 5.1+; checks the existing environment without changing the database.
$ErrorActionPreference = 'Stop'
Push-Location -LiteralPath $PSScriptRoot
try {
    if (-not (Test-Path -LiteralPath '.venv\Scripts\python.exe' -PathType Leaf)) {
        throw 'Python environment is missing. Run setup.ps1 first.'
    }
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        throw 'Docker is unavailable. Start Docker Desktop and make docker available in PATH.'
    }

    $runningContainers = @(docker compose ps --status running -q db)
    if ($LASTEXITCODE -ne 0) {
        throw 'Cannot inspect PostgreSQL. Check Docker Desktop and run setup.ps1.'
    }
    if (-not $runningContainers.Count) {
        throw 'PostgreSQL container is not running. Run setup.ps1 first.'
    }

    Write-Host 'Checking database version, locale, authentication and privileges...'
    docker compose exec -T db /usr/local/bin/verify-db.sh
    if ($LASTEXITCODE -ne 0) { throw 'Database configuration verification failed.' }

    Write-Host 'Running unit tests...'
    & .\.venv\Scripts\python.exe -m unittest discover -s tests -v
    if ($LASTEXITCODE -ne 0) { throw 'Unit tests failed.' }

    if (-not (Test-Path -LiteralPath '.env' -PathType Leaf)) {
        throw '.env is missing. Run setup.ps1 before the live database tests.'
    }
    # Parse data only: never dot-source .env or evaluate its contents.
    $passwordLines = @(Get-Content -LiteralPath '.env' | Where-Object { $_ -match '^\s*APP_DB_PASSWORD\s*=' })
    if ($passwordLines.Count -ne 1) {
        throw '.env must contain exactly one APP_DB_PASSWORD entry.'
    }
    $appPassword = ($passwordLines[0] -split '=', 2)[1].Trim()
    if ($appPassword.Length -ge 2 -and $appPassword[0] -eq "'" -and $appPassword[-1] -eq "'") {
        $appPassword = $appPassword.Substring(1, $appPassword.Length - 2)
    } elseif ($appPassword.Length -ge 2 -and $appPassword[0] -eq '"' -and $appPassword[-1] -eq '"') {
        $appPassword = $appPassword.Substring(1, $appPassword.Length - 2)
        if ($appPassword.Contains('$') -or $appPassword.Contains('\')) {
            throw 'Escapes and variable interpolation are unsupported here. Use the plain .env generated by setup.ps1.'
        }
    } else {
        $appPassword = ($appPassword -replace '\s+#.*$', '').TrimEnd()
        if ($appPassword.Contains('$')) {
            throw 'Variable interpolation is unsupported here. Use the plain .env generated by setup.ps1.'
        }
    }
    if ([string]::IsNullOrEmpty($appPassword)) {
        throw 'APP_DB_PASSWORD in .env must not be empty.'
    }

    $hadPassword = Test-Path Env:APP_DB_PASSWORD
    $previousPassword = $env:APP_DB_PASSWORD
    try {
        $env:APP_DB_PASSWORD = $appPassword
        Write-Host 'Running live application integration tests...'
        & .\.venv\Scripts\python.exe -m unittest discover -s integration -v
        if ($LASTEXITCODE -ne 0) { throw 'Live database integration tests failed.' }
    } finally {
        if ($hadPassword) {
            $env:APP_DB_PASSWORD = $previousPassword
        } else {
            Remove-Item Env:APP_DB_PASSWORD -ErrorAction SilentlyContinue
        }
        $appPassword = $null
        $previousPassword = $null
    }
    Write-Host 'Verification passed: database checks, unit tests and live application tests.' -ForegroundColor Green
} finally {
    Pop-Location
}
